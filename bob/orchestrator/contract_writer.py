"""
Contract Writer — Writes verification tests as real .py files.
================================================================

Replaces the old approach of embedding tests as triple-escaped strings
in JSON. Tests are now proper pytest files in `.bob/contracts/`.

Each contract file includes:
1. Real pytest test functions generated from Claude output
2. Meta-tests that validate the test file itself (self-checking)

Validation pipeline:
1. ast.parse() — syntax check
2. compile() — bytecode compilation check
3. AST analysis — assertion count, no trivial 'assert True'
4. Meta-test execution — pytest -k 'test_meta' on the file
"""

