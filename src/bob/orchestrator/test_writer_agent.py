def emit_failing_tests(
    feature_id: str,
    acceptance_criteria: list[str],
    workspace: str | Path | None = None,
) -> list[EmittedTest]:
    """Write one failing pytest file per acceptance criterion.

    Files are placed under ``<workspace>/tests/<feature_id>/test_<ac_id>.py``.
    An ``__init__.py`` is created in the output directory if absent.

    Args:
        feature_id: UUID (or any string) identifying the feature.
        acceptance_criteria: List of AC strings.
        workspace: Root of the project.  Defaults to ``Path.cwd()``.

    Returns:
        List of EmittedTest metadata objects (one per AC).
    """
    root = Path(workspace) if workspace else Path.cwd()
    out_dir = root / "tests" / feature_id
    out_dir.mkdir(parents=True, exist_ok=True)

    init = out_dir / "__init__.py"
    if not init.exists():
        init.write_text("", encoding="utf-8")

    emitted: list[EmittedTest] = []
    for idx, ac_text in enumerate(acceptance_criteria):
        ac_id = _ac_id(idx, ac_text)
        test_path = out_dir / f"test_{ac_id}.py"
        content = _render_test(feature_id, idx, ac_text, ac_id)
        test_path.write_text(content, encoding="utf-8")
        logger.debug("Emitted failing test: %s", test_path)
        emitted.append(
            EmittedTest(
                ac_index=idx,
                ac_id=ac_id,
                ac_text=ac_text,
                test_path=test_path,
                feature_id=feature_id,
            )
        )

    logger.info(
        "emit_failing_tests: wrote %d test file(s) for feature %s",
        len(emitted),
        feature_id[:8],
    )
    return emitted


