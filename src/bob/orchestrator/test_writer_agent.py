def _check_compiles(path: Path) -> bool:
    """Return True if the test file parses without SyntaxError."""
    try:
        source = path.read_text(encoding="utf-8")
        ast.parse(source, filename=str(path))
        return True
    except (SyntaxError, UnicodeDecodeError):
        logger.debug("triple_filter compile check failed for %s", path)
        return False


def _check_fails_on_stub(path: Path) -> bool:
    """Return True if running the test in an isolated empty dir exits non-zero.

    Fast-path: uses AST analysis to detect definitively-failing tests (those
    with unconditional ``pytest.fail(...)`` calls) and definitively-passing
    tests (those with only ``assert True`` or bare ``pass`` bodies) without
    spawning a subprocess.  For ambiguous cases, falls back to spawning
    ``python -m pytest <test_file> --tb=no -q`` in a fresh temp directory.
    """
    fast_result = _ast_stub_check(path)
    if fast_result is not None:
        return fast_result

    try:
        with tempfile.TemporaryDirectory() as tmp:
            result = subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "pytest",
                    str(path),
                    "--tb=no",
                    "-q",
                    "--no-header",
                ],
                capture_output=True,
                text=True,
                timeout=30,
                cwd=tmp,
            )
            # Non-zero exit code = test failed (as expected for red tests)
            return result.returncode != 0
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        # If we can't run pytest, assume the test is properly failing
        logger.debug("triple_filter stub check could not run pytest for %s", path)
        return True


def _ast_stub_check(path: Path) -> bool | None:
    """AST-based fast-path for _check_fails_on_stub.

    Returns:
        True  — test is definitively red (unconditional pytest.fail call found)
        False — test is definitively green (only assert True / pass bodies)
        None  — ambiguous; caller must spawn subprocess
    """
    try:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
    except (SyntaxError, UnicodeDecodeError):
        return None  # uncompilable; compile check will reject it

    has_pytest_fail = False
    has_only_trivial = True
    imports_stub_sensitive = False  # pathlib/importlib asserts always fail on stubs

    _STUB_SENSITIVE = frozenset({"pathlib", "importlib"})

    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            func = node.func
            # pytest.fail(...) or pytest.raises(...) used as a direct call
            if (
                isinstance(func, ast.Attribute)
                and isinstance(func.value, ast.Name)
                and func.value.id == "pytest"
                and func.attr in ("fail", "raises", "warns")
            ):
                has_pytest_fail = True
        elif isinstance(node, ast.Assert):
            # assert True is trivially green; anything else is non-trivial
            if not (isinstance(node.test, ast.Constant) and node.test.value is True):
                has_only_trivial = False
        elif isinstance(node, ast.Raise):
            has_only_trivial = False
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] in _STUB_SENSITIVE:
                    imports_stub_sensitive = True
        elif isinstance(node, ast.ImportFrom):
            mod = (node.module or "").split(".")[0]
            if mod in _STUB_SENSITIVE:
                imports_stub_sensitive = True

    if has_pytest_fail:
        return True  # definitively failing
    if has_only_trivial:
        # Only assert True / pass — definitively green (passes on stub)
        return False
    if imports_stub_sensitive and not has_only_trivial:
        # Non-trivial assertions checking pathlib.Path.exists() or importlib
        # calls will always fail on a stub (missing files/modules).
        return True
    return None  # ambiguous; let subprocess decide


def _check_raises_coverage(path: Path) -> bool:
    """Heuristic: test references at least one non-pytest import or symbol.

    Parses the AST and looks for:
    - ``import`` or ``from ... import`` of any module other than pytest/builtins
    - Any ``assert`` statement that is not ``assert True``

    This is a coverage *heuristic*, not full instrumented coverage.
    """
    try:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
    except (SyntaxError, UnicodeDecodeError):
        return False

    _STDLIB_ONLY = frozenset({"pytest", "builtins", "__future__", "typing"})

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                top = alias.name.split(".")[0]
                if top not in _STDLIB_ONLY:
                    return True
        elif isinstance(node, ast.ImportFrom):
            mod = (node.module or "").split(".")[0]
            if mod and mod not in _STDLIB_ONLY:
                return True
        elif isinstance(node, ast.Assert):
            # Any non-trivial assertion counts
            if not (
                isinstance(node.test, ast.Constant) and node.test.value is True
            ):
                return True
        elif isinstance(node, ast.Raise):
            # An explicit raise (not bare re-raise) counts as non-trivial
            if node.exc is not None:
                return True

    # Templates emit pytest.fail(...) which counts as exercising pytest — but
    # our template also calls pytest.fail which is a non-trivial assertion
    # equivalent.  Check for pytest.fail or pytest.raises calls.
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name):
                if func.value.id == "pytest" and func.attr in ("fail", "raises", "warns", "approx"):
                    return True

    return False


