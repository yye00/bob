class UncompilableTestError(Exception):
    """Raised by reject_uncompilable when a test file fails py_compile."""


class StubPassError(Exception):
    """Raised by reject_passes_on_stub when a test passes against a stub."""


class NoCoverageUpliftError(Exception):
    """Raised by reject_no_coverage_uplift when a test doesn't cover its AC region."""


# ---------------------------------------------------------------------------
# Public: reject_* convenience wrappers (raising variants of triple_filter)
# ---------------------------------------------------------------------------


def reject_uncompilable(path: "str | Path") -> None:
    """Raise UncompilableTestError if the test file at *path* fails py_compile.

    Passes silently when the file compiles without errors.

    Args:
        path: Path to the test file to validate.

    Raises:
        UncompilableTestError: When the file has a SyntaxError or cannot be parsed.
    """
    import py_compile  # stdlib; import here to keep top-level imports light

    path = Path(path)
    try:
        py_compile.compile(str(path), doraise=True)
    except py_compile.PyCompileError as exc:
        raise UncompilableTestError(
            f"Test file {path} failed py_compile: {exc}"
        ) from exc


def reject_passes_on_stub(path: "str | Path") -> None:
    """Raise StubPassError if the test at *path* passes against an empty stub.

    An empty stub means no source modules are installed — the test is run in
    a fresh temporary directory.  If the test exits 0 (green) under those
    conditions it is not genuinely red and must be rejected.

    Args:
        path: Path to the test file to validate.

    Raises:
        StubPassError: When the test exits 0 against an empty stub environment.
    """
    path = Path(path)
    try:
        with tempfile.TemporaryDirectory() as tmp:
            result = subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "pytest",
                    str(path),
                    "--tb=no",
                    "-q",
                    "--no-header",
                ],
                capture_output=True,
                text=True,
                timeout=30,
                cwd=tmp,
            )
            if result.returncode == 0:
                raise StubPassError(
                    f"Test {path} passes against empty stub (exit 0) — "
                    "mysteriously green; test must be genuinely red before implementation."
                )
    except subprocess.TimeoutExpired:
        # A timeout means something is running (not silently passing)
        logger.debug("reject_passes_on_stub: pytest timed out for %s — treating as not-passing", path)


def reject_no_coverage_uplift(path: "str | Path", ac_region: str | None = None) -> None:
    """Raise NoCoverageUpliftError if the test doesn't reference the AC-named region.

    Uses the same heuristic as ``_check_raises_coverage``: the test must import
    at least one non-pytest symbol or contain a non-trivial assertion or
    pytest.fail/raises call.  When *ac_region* is provided the test source is
    additionally scanned for a literal reference to that region string.

    Args:
        path: Path to the test file.
        ac_region: Optional AC-named region (e.g. a module or function name).
                   When given, the test must reference this string somewhere.

    Raises:
        NoCoverageUpliftError: When the test fails the coverage heuristic.
    """
    path = Path(path)
    if not _check_raises_coverage(path):
        raise NoCoverageUpliftError(
            f"Test {path} does not reference any non-pytest symbol — "
            "no coverage uplift of the AC-named region detected."
        )
    if ac_region:
        try:
            source = path.read_text(encoding="utf-8")
        except OSError:
            raise NoCoverageUpliftError(
                f"Test {path} could not be read for AC-region coverage check."
            )
        if ac_region not in source:
            raise NoCoverageUpliftError(
                f"Test {path} does not reference the AC-named region {ac_region!r}."
            )
