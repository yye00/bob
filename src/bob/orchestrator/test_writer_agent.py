_TEST_TEMPLATE = textwrap.dedent(
    '''\
    """Failing test for AC-{ac_index}: {ac_text_short}

    This file is generated by the test-writer sub-agent before the
    implementer fires.  It must FAIL before implementation and PASS
    after a correct implementation.

    AC (verbatim): {ac_text}
    Feature-ID:    {feature_id}
    AC-ID:         {ac_id}
    """

    from __future__ import annotations

    import pytest


    class Test{class_name}:
        """Acceptance criterion: {ac_text_short}"""

        def test_{ac_id}_not_yet_implemented(self):
            """RED: this test must fail until the feature is implemented.

            Replace this body with real assertions once the feature exists.
            """
            pytest.fail(
                "AC not yet implemented: {ac_text_short!r} — "
                "replace with real assertions after implementation."
            )
    '''
)


def _class_name(ac_id: str) -> str:
    parts = ac_id.split("_")
    return "".join(p.capitalize() for p in parts if p)


def _render_real_structural_test(
    feature_id: str, ac_index: int, ac_text: str, ac_id: str
) -> str | None:
    """Generate a REAL per-AC test for a structural AC, or None if not structural.

    Structural ACs ("File exists", "Function defined", "Class defined",
    "integration:") fully specify what to check, so the test-writer can emit a
    genuine assertion instead of a RED placeholder. The test fails before
    implementation (file/symbol absent) and passes after — true RED→GREEN — and
    is a durable regression test rather than an unreplaced stub. Non-structural
    ACs return None (caller falls back to the RED stub the implementer must
    flesh out). 2026-06-20 deepen — see draining-vs-correct-implementation.
    """
    import re as _re
    s = ac_text.strip()
    low = s.lower()
    short = s[:72].replace("\n", " ")
    cls = _class_name(ac_id)
    header = (
        f'"""Real structural test for AC-{ac_index}: {short}\n\n'
        f"AC (verbatim): {s}\nFeature-ID: {feature_id}\nAC-ID: {ac_id}\n"
        '"""\nfrom __future__ import annotations\nimport importlib, pathlib\n\n\n'
    )

    # Identifiers/paths are interpolated at GENERATION time into double-quoted
    # literals (they contain no double quotes), and assertion messages are plain
    # (non-f) strings — this avoids nested-quote syntax errors in the emitted file.
    def _ident_ok(x: str) -> bool:
        return bool(_re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]*", x or ""))

    if low.startswith("file exists:"):
        path = s.split(":", 1)[1].strip().split()[0].lstrip("/")
        if path.startswith("workspace/"):
            path = path[len("workspace/"):]
        if '"' in path or "\n" in path:
            return None
        return header + (
            f"def test_{ac_id}_file_exists():\n"
            f'    p = pathlib.Path("{path}")\n'
            f"    pkg = p.with_suffix('') / '__init__.py' if p.suffix == '.py' else None\n"
            f"    assert p.exists() or (pkg is not None and pkg.exists()), "
            f'"required file missing: {path}"\n'
        )

    if low.startswith("function defined:") or low.startswith("class defined:"):
        dotted = _re.split(r"\s+\(", s.split(":", 1)[1].strip(), maxsplit=1)[0].strip()
        if "." in dotted:
            mod, sym = dotted.rsplit(".", 1)
        else:
            mod, sym = "bob", dotted
        if not (_ident_ok(mod) and _ident_ok(sym)):
            return None
        kind = "class" if low.startswith("class defined:") else "function"
        chk = "isinstance(obj, type)" if kind == "class" else "callable(obj)"
        return header + (
            f"def test_{ac_id}_{kind}_defined():\n"
            f'    m = importlib.import_module("{mod}")\n'
            f'    assert hasattr(m, "{sym}"), "{kind} {sym} not defined in {mod}"\n'
            f'    obj = getattr(m, "{sym}")\n'
            f'    assert {chk}, "{sym} exists but is not a {kind}"\n'
        )

    if low.startswith("integration:"):
        body = s.split(":", 1)[1].strip()
        m = _re.search(r"\b([a-zA-Z_][\w]*(?:\.[a-zA-Z_][\w]*)+)\b", body)
        if m and _ident_ok(m.group(1)):
            mod = m.group(1)
            return header + (
                f"def test_{ac_id}_integration_importable():\n"
                f"    import importlib.util\n"
                f'    assert importlib.util.find_spec("{mod}") is not None, '
                f'"integration target not importable: {mod}"\n'
            )
    return None


def _render_test(feature_id: str, ac_index: int, ac_text: str, ac_id: str) -> str:
    real = _render_real_structural_test(feature_id, ac_index, ac_text, ac_id)
    if real is not None:
        return real
    short = ac_text[:72].replace("\n", " ")
    return _TEST_TEMPLATE.format(
        ac_index=ac_index,
        ac_text=ac_text,
        ac_text_short=short,
        feature_id=feature_id,
        ac_id=ac_id,
        class_name=_class_name(ac_id),
    )


