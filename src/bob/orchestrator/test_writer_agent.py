def verify_bijection(
    feature_id: str,
    acceptance_criteria: list[str],
    workspace: str | Path | None = None,
) -> BijectionReport:
    """Confirm a bijection between ACs and test files.

    Every AC must have exactly one ``test_<ac_id>.py`` under
    ``tests/<feature_id>/``, and every such file must map back to a
    declared AC.

    Args:
        feature_id: Feature identifier.
        acceptance_criteria: Declared list of AC strings.
        workspace: Project root.  Defaults to ``Path.cwd()``.

    Returns:
        BijectionReport with ``is_bijective=True`` iff no missing or orphan
        tests were found.
    """
    root = Path(workspace) if workspace else Path.cwd()
    out_dir = root / "tests" / feature_id

    expected_ac_ids = [_ac_id(i, ac) for i, ac in enumerate(acceptance_criteria)]

    # Collect test files that match our naming convention
    if out_dir.exists():
        found_files = sorted(p.name for p in out_dir.glob("test_*.py"))
    else:
        found_files = []

    # Build mapping: ac_id -> expected filename
    expected_files = {f"test_{ac_id}.py" for ac_id in expected_ac_ids}

    missing_tests = [
        ac_id for ac_id in expected_ac_ids
        if f"test_{ac_id}.py" not in found_files
    ]
    orphan_tests = [
        fname for fname in found_files
        if fname not in expected_files and fname != "__init__.py"
    ]

    is_bijective = not missing_tests and not orphan_tests

    return BijectionReport(
        is_bijective=is_bijective,
        missing_tests=missing_tests,
        orphan_tests=orphan_tests,
        ac_ids=expected_ac_ids,
        test_paths=[str(out_dir / f"test_{ac_id}.py") for ac_id in expected_ac_ids],
    )


