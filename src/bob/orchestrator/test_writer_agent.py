def triple_filter(
    emitted_tests: list[EmittedTest],
    workspace: str | Path | None = None,
) -> list[FilterResult]:
    """Apply the TestGen-LLM triple filter to each emitted test file.

    The three checks:
    1. **Compile**: ``py_compile`` / AST parse succeeds.
    2. **Fails on stub**: Running the test against a minimal stub (i.e. an
       empty temp directory with no source modules) returns non-zero exit code,
       meaning the test is genuinely red when nothing is implemented.
    3. **Raises coverage**: Heuristic — the test imports or references
       at least one symbol that isn't pytest itself, meaning it exercises
       real code rather than being a vacuous no-op.

    Args:
        emitted_tests: List of EmittedTest objects from ``emit_failing_tests``.
        workspace: Project root.  Used to resolve test paths.

    Returns:
        List of FilterResult, one per input test.
    """
    results: list[FilterResult] = []
    for et in emitted_tests:
        path = et.test_path

        # ---- Check 1: compiles ----
        compiles = _check_compiles(path)
        if not compiles:
            results.append(
                FilterResult(
                    test_path=path,
                    ac_id=et.ac_id,
                    compiles=False,
                    fails_on_stub=False,
                    raises_coverage=False,
                    accepted=False,
                    reason="SyntaxError or uncompilable — test rejected",
                )
            )
            continue

        # ---- Check 2: fails on stub ----
        fails_on_stub = _check_fails_on_stub(path)
        if not fails_on_stub:
            results.append(
                FilterResult(
                    test_path=path,
                    ac_id=et.ac_id,
                    compiles=True,
                    fails_on_stub=False,
                    raises_coverage=False,
                    accepted=False,
                    reason="Test passes on stub code — no coverage of AC-named symbol, rejected",
                )
            )
            continue

        # ---- Check 3: raises coverage heuristic ----
        raises_coverage = _check_raises_coverage(path)

        accepted = raises_coverage
        reason = "" if accepted else "Test does not reference any non-pytest symbol — coverage check failed"

        results.append(
            FilterResult(
                test_path=path,
                ac_id=et.ac_id,
                compiles=True,
                fails_on_stub=True,
                raises_coverage=raises_coverage,
                accepted=accepted,
                reason=reason,
            )
        )

    return results


