@dataclass
class EmittedTest:
    """Metadata about a single emitted test file."""

    ac_index: int
    ac_id: str          # slugified, e.g. "ac_0", "ac_1"
    ac_text: str
    test_path: Path     # tests/<feature_id>/test_<ac_id>.py
    feature_id: str


@dataclass
class BijectionReport:
    """Result of verify_bijection."""

    is_bijective: bool
    missing_tests: list[str]        # AC IDs with no matching test file
    orphan_tests: list[str]         # test files with no matching AC
    ac_ids: list[str]
    test_paths: list[str]


@dataclass
class FilterResult:
    """Result of triple_filter for one test file."""

    test_path: Path
    ac_id: str
    compiles: bool
    fails_on_stub: bool             # True = correctly fails (desired)
    raises_coverage: bool           # True = passes the coverage heuristic
    accepted: bool                  # True = all three checks passed
    reason: str = ""                # populated when accepted=False


