_SAFE_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slugify(text: str, index: int) -> str:
    """Convert AC text to a filesystem-safe slug, fall back to ac_<index>."""
    slug = _SAFE_SLUG_RE.sub("_", text.lower()).strip("_")[:40]
    return slug if slug else f"ac_{index}"


def _ac_id(index: int, ac_text: str) -> str:
    """Return the canonical ac_id for an acceptance criterion."""
    return f"ac_{index}_{_slugify(ac_text, index)}"


