"""Test-writer sub-agent — emit one failing pytest per AC before implementer fires.

Inserts between spec-critic (F-R7-450) and the implementer sub-agent.

Given a validated feature spec, ``emit_failing_tests`` writes one
``tests/<feature_id>/test_<ac_id>.py`` per acceptance criterion.  The
implementer receives the spec AND the failing tests; its definition of
done is "all AC-tagged tests now pass".

``verify_bijection`` confirms that the AC↔test mapping is bijective:
every AC has exactly one test file, and every such file maps back to a
declared AC.

``triple_filter`` rejects tests that:
  1. Don't compile (SyntaxError / ImportError at collection time)
  2. Mysteriously pass on stub code (test passes when the module it
     exercises does not exist or raises NotImplementedError)
  3. Fail to raise coverage of the AC-named region (placeholder — full
     AST-coverage integration is out of scope for this module)

Public API::

    from bob.orchestrator.test_writer_agent import (
        emit_failing_tests,
        verify_bijection,
        triple_filter,
    )

Source: Agent 4 §9 + AC-F-TEST-FIRST-CASCADE-1, Agent 2 §AutoUAT,
Agent 3 §predicate_coverage sub-metric.
"""

