def emit_failing_test(
    feature_id: str,
    ac_index: int,
    ac_text: str,
    *,
    workspace: "str | Path | None" = None,
) -> EmittedTest:
    """Emit a single failing pytest file for one acceptance criterion.

    Writes ``tests/<feature_id>/test_<ac_id>.py`` (creating intermediate
    directories and ``__init__.py`` as needed).

    Args:
        feature_id: Unique feature identifier (UUID or any filesystem-safe string).
        ac_index: Zero-based index of this AC within the feature's AC list.
        ac_text: The full acceptance criterion text.
        workspace: Project root directory; defaults to ``Path.cwd()``.

    Returns:
        EmittedTest metadata for the written file.

    Raises:
        ValueError: When ``feature_id`` is empty or ``ac_text`` is not a string.
    """
    if not isinstance(feature_id, str) or not feature_id.strip():
        raise ValueError(
            f"feature_id must be a non-empty string, got {feature_id!r}"
        )
    if not isinstance(ac_text, str):
        raise ValueError(
            f"ac_text must be a string, got {type(ac_text).__name__!r}"
        )

    root = Path(workspace) if workspace else Path.cwd()
    out_dir = root / "tests" / feature_id
    out_dir.mkdir(parents=True, exist_ok=True)

    init = out_dir / "__init__.py"
    if not init.exists():
        init.write_text("", encoding="utf-8")

    ac_id = _ac_id(ac_index, ac_text)
    test_path = out_dir / f"test_{ac_id}.py"
    content = _render_test(feature_id, ac_index, ac_text, ac_id)
    test_path.write_text(content, encoding="utf-8")

    return EmittedTest(
        ac_index=ac_index,
        ac_id=ac_id,
        ac_text=ac_text,
        test_path=test_path,
        feature_id=feature_id,
    )


# ---------------------------------------------------------------------------
# Public: generate_failing_tests (AC-required alias with extended return type)
# ---------------------------------------------------------------------------


def generate_failing_tests(
    feature_id: str,
    acceptance_criteria: list[str],
    *,
    workspace: "str | Path | None" = None,
) -> dict[str, Any]:
    """Generate failing tests for each acceptance criterion before implementation.

    Alias for the full test-writer pipeline:
    1. emit_failing_tests — write one test file per AC
    2. triple_filter — reject tests that don't compile, pass on stub, or lack coverage
    3. verify_bijection — confirm AC↔test bijection

    Args:
        feature_id: Unique feature identifier (UUID or slug).
        acceptance_criteria: Ordered list of AC strings for this feature.
        workspace: Project root directory; defaults to ``Path.cwd()``.

    Returns:
        dict with keys:
            emitted: list[EmittedTest]
            filter_results: list[FilterResult]
            bijection: BijectionReport
            gate_passed: bool — True when all triple-filter checks pass and bijection is satisfied

    Raises:
        ValueError: When ``feature_id`` is empty or ``acceptance_criteria`` is not a list.
    """
    if not isinstance(feature_id, str) or not feature_id.strip():
        raise ValueError(f"feature_id must be a non-empty string, got {feature_id!r}")
    if not isinstance(acceptance_criteria, list):
        raise ValueError(
            f"acceptance_criteria must be a list, got {type(acceptance_criteria).__name__!r}"
        )

    emitted: list[EmittedTest] = emit_failing_tests(
        feature_id,
        acceptance_criteria,
        workspace=workspace,
    )

    filter_results: list[FilterResult] = triple_filter(emitted, workspace=workspace)

    bijection: BijectionReport = verify_bijection(
        feature_id,
        acceptance_criteria,
        workspace=workspace,
    )

    all_accepted = all(r.accepted for r in filter_results)
    gate_passed = all_accepted and bijection.is_bijective

    return {
        "emitted": emitted,
        "filter_results": filter_results,
        "bijection": bijection,
        "gate_passed": gate_passed,
    }


